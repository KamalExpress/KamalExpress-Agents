#!/usr/bin/env python3
"""
Documentation Synchronization Script for Kamal Express AI Platform.
Indexes all repository markdown specifications and updates `docs/docs_data.js`
for instant in-browser runtime rendering in `docs/index.html`.
"""

import os
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

# Add Alamia-Skills-System to sys.path if available
alamia_core = REPO_ROOT / "Alamia-Skills-System"
if alamia_core.exists() and str(alamia_core) not in sys.path:
    sys.path.insert(0, str(alamia_core))

try:
    from core.doc_engine import DocEngine
    engine = DocEngine(project_root=REPO_ROOT)
    result = engine.sync()
    print(f"[SUCCESS] Synchronized {result['total_documents']} documentation files into {result['output_file']}")
except Exception as e:
    # Direct fallback indexer
    import json
    docs_dir = REPO_ROOT / "docs"
    docs_data_file = docs_dir / "docs_data.js"
    docs_payload = []
    seen = set()

    # Prioritize master README
    master_readme = docs_dir / "README.md"
    if master_readme.exists():
        seen.add(master_readme)
        docs_payload.append({
            "id": "master-index",
            "title": "Master Index & AI Bootstrap Read Order",
            "category": "Overview",
            "path": "docs/README.md",
            "description": "Master Index with official AI bootstrap read order and directory map.",
            "markdown": master_readme.read_text(encoding="utf-8", errors="replace"),
            "line_count": len(master_readme.read_text(encoding="utf-8", errors="replace").splitlines()),
        })

    for root, _, files in os.walk(docs_dir):
        for f in sorted(files):
            if f.endswith(".md"):
                full_p = Path(root) / f
                if full_p in seen:
                    continue
                seen.add(full_p)
                content = full_p.read_text(encoding="utf-8", errors="replace")
                
                # Title
                title = full_p.stem.replace("-", " ").replace("_", " ").title()
                for l in content.splitlines():
                    if l.startswith("# "):
                        title = l[2:].strip()
                        break

                rel_parts = full_p.relative_to(docs_dir).parts
                cat = "General"
                if len(rel_parts) > 1:
                    cat = rel_parts[0].capitalize()
                    if cat.lower() in ["permanent", "transient"] and len(rel_parts) > 2:
                        cat = rel_parts[1].capitalize()

                docs_payload.append({
                    "id": full_p.stem.lower().replace(" ", "-"),
                    "title": title,
                    "category": cat,
                    "path": str(full_p.relative_to(REPO_ROOT)).replace("\\", "/"),
                    "description": f"Documentation: {title}",
                    "markdown": content,
                    "line_count": len(content.splitlines()),
                })

    # External specifications
    for ext_path, cat, desc in [
        (REPO_ROOT / "standalone_workers" / "WORKFLOW_SPECIFICATION.md", "Workers", "Authoritative Scout & Booker Specification"),
        (REPO_ROOT / "README.md", "Overview", "Kamal Express Platform Overview"),
        (REPO_ROOT / "RUNNING.md", "Operations", "Local Running & Launching Guide"),
    ]:
        if ext_path.exists() and ext_path not in seen:
            seen.add(ext_path)
            content = ext_path.read_text(encoding="utf-8", errors="replace")
            title = ext_path.stem.replace("-", " ").title()
            for l in content.splitlines():
                if l.startswith("# "):
                    title = l[2:].strip()
                    break
            docs_payload.append({
                "id": ext_path.stem.lower().replace(" ", "-"),
                "title": title,
                "category": cat,
                "path": str(ext_path.relative_to(REPO_ROOT)).replace("\\", "/"),
                "description": desc,
                "markdown": content,
                "line_count": len(content.splitlines()),
            })

    js_code = (
        "// Auto-generated by scripts/sync_docs.py - Do not edit directly\n"
        "window.DOCS_DATA = " + json.dumps(docs_payload, indent=2, ensure_ascii=False) + ";\n"
    )
    docs_data_file.write_text(js_code, encoding="utf-8")
    print(f"[SUCCESS] Synchronized {len(docs_payload)} documentation files into {docs_data_file}")
